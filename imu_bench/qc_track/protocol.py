# ------------------------------------------- (선택) 스크립트 자극 — L/T 분리
#
# teleop 만으로는 상호상관 실효 지연 하나밖에 못 낸다. 그 값은 **그 운동의
# 스펙트럼에 딸린 값**이라 조건이 바뀌면 바뀐다. 순수지연 L 과 1 차 지체 T 를
# 가르려면 구간마다 한 주파수로 흔들어 위상·이득 곡선을 얻어야 한다
# (Exp-Latency §3.1). 그건 손으로는 못 한다.
#
# 그래서 desired_twist 에 사인을 직접 실어 로봇이 스스로 흔들게 한다. 진폭은
# probe.yaml 의 안전 한계 **아래**로 잡는다 — 넘어가면 재는 것이 레이턴시가
# 아니라 클리핑이 된다.
# 축 정의: tilt 는 base +y 둘레(침투축이 base x 쪽으로 기운다 -> 분석기의 tip_x),
# roll 은 침투축 둘레(-> spin), trans 는 base x 방향 병진.
FREQS = {"tilt": (0.15, 0.30, 0.60, 1.00, 1.60),
         "roll": (0.15, 0.30, 0.60, 1.00, 1.60),
         "trans": (0.15, 0.30, 0.60, 1.00)}

# 각속도/속도 첨두 예산. freespace 프로파일의 상한(1.5 rad/s, 0.15 m/s)의 약 1/5 다.
# 여유를 크게 두는 이유: IK 가 특이점 근처에서 큰 관절속도를 내고, 그때 서보 단
# 클램프가 물면 그 구간의 위상을 못 믿게 된다.
W_BUDGET = 0.30              # rad/s 첨두
V_BUDGET = 0.030             # m/s 첨두
ANG_AMP_MAX_DEG = 20.0
LIN_AMP_MAX_MM = 30.0
MIN_CYCLES = 6
MIN_SECONDS = 12.0
SETTLE_S = 2.0
LEAD_S = 1.5                 # 구간 앞뒤의 정지. 위상 0 과 기준선을 잡는 자리


def raised_cosine(s):
    """0..1 -> 0..1 포락선. 사인 구간의 시작/끝을 부드럽게 연다.

    갑자기 진폭을 세우면 그 계단이 모든 주파수를 때려 록인 잔차가 커진다.
    러너와 시뮬레이터가 **같은 창**을 써야 하므로 여기 둔다.
    """
    return 0.5 * (1.0 - np.cos(np.pi * np.clip(s, 0.0, 1.0)))


def ang_amplitude_deg(f):
    """두 천장 중 낮은 것. 어느 것이 물었는지도 같이 돌려준다."""
    caps = {"amp": ANG_AMP_MAX_DEG, "speed": np.degrees(W_BUDGET / (2 * np.pi * f))}
    which = min(caps, key=caps.get)
    return float(caps[which]), which


def lin_amplitude_mm(f):
    caps = {"amp": LIN_AMP_MAX_MM, "speed": V_BUDGET / (2 * np.pi * f) * 1000.0}
    which = min(caps, key=caps.get)
    return float(caps[which]), which


def segment_seconds(f):
    return float(max(MIN_SECONDS, MIN_CYCLES / f))


def plan_sweep(axis):
    """구간 목록. axis: tilt | roll | trans."""
    out = []
    for f in FREQS[axis]:
        if axis == "trans":
            A, cap = lin_amplitude_mm(f)
            out.append(dict(freq_hz=f, amp_mm=A, cap=cap, unit="mm",
                            seconds=segment_seconds(f),
                            peak_rate=2 * np.pi * f * A / 1000.0))
        else:
            A, cap = ang_amplitude_deg(f)
            out.append(dict(freq_hz=f, amp_deg=A, cap=cap, unit="deg",
                            seconds=segment_seconds(f),
                            peak_rate=np.radians(A) * 2 * np.pi * f))
    return out


def sweep_seconds(axis):
    return sum(s["seconds"] + 2 * LEAD_S + SETTLE_S for s in plan_sweep(axis))


def describe():
    """사람이 읽는 계획 요약. run_session.py --dry-run 이 찍는다."""
    lines = ["블록          길이        무엇"]
    for b in DEFAULT_BLOCKS:
        lines.append(f"  {b:<12s} {DURATION[b]:6.0f} s   {PROMPTS[b][0]}")
    for a in ("tilt", "roll", "trans"):
        lines.append(f"  sweep_{a:<7s}{sweep_seconds(a):6.0f} s   (선택) "
                     f"{len(FREQS[a])} 주파수 {FREQS[a][0]}~{FREQS[a][-1]} Hz")
    return "\n".join(lines)


def plan_mag_map():
    """스크립트 mag_map 의 다리 목록. ROS 없이 계산된다 (--dry-run 이 이걸 찍는다).

    한 자세 묶음 = 시작점에서 별 모양 5 자리. 원점으로 돌아오지 않고 바로 다음
    자리로 가면 다리가 짧아지지만, 그러면 쌍의 위치차가 축 하나에만 실린다.
    원점을 거쳐 가면 +x 와 -x 가 2*STEP 만큼 벌어져 쌍이 고르게 퍼진다.

    돌려주는 것은 (kind, payload) 목록이다 — 'move' 는 시작점 기준 목표 오프셋
    [mm], 'hold' 는 정지, 'turn' 은 base 축 둘레 회전 [deg].
    """
    step = MAG_MAP_STEP_MM
    star = [(0, 0, 0), (step, 0, 0), (-step, 0, 0), (0, step, 0), (0, 0, step)]
    turns = [(0, 0, 1), (0, 1, 0)]              # 묶음 사이의 회전축 (base 프레임)
    legs = []
    for k in range(MAG_MAP_POSES):
        for off in star:
            legs.append(("move", off))
            legs.append(("hold", MAG_MAP_DWELL_S))
        if k < MAG_MAP_POSES - 1:
            legs.append(("move", (0, 0, 0)))    # 회전은 원점에서 한다
            legs.append(("turn", (turns[k % len(turns)], MAG_MAP_TURN_DEG)))
    return legs


def mag_map_seconds():
    """스크립트 mag_map 의 대략적인 길이 [s]. 이동 거리는 직전 자리에서 잰다."""
    import math
    t, cur = 0.0, (0.0, 0.0, 0.0)
    for kind, payload in plan_mag_map():
        if kind == "move":
            d = math.dist(cur, payload)
            t += d / MAG_MAP_V_MMS + 1.0        # 가감속 몫을 1 s 로 본다
            cur = payload
        elif kind == "hold":
            t += payload
        else:
            t += payload[1] / MAG_MAP_W_DEG_S + 1.0
    return t
